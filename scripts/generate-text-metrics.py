"""Regenerate Standard 14 visible glyph bounds with the dev PDFium renderer.

Metrics are unit-em geometry, not font programs. Keep the Python/browser and
TypeScript copies identical. Runtime stamping does not need PDFium rendering.
"""
import io
import json
from pathlib import Path

import pypdfium2
from reportlab.pdfgen import canvas

root = Path(__file__).resolve().parents[1]
metrics = {}
for font in ('Helvetica', 'Helvetica-Oblique'):
    chars = []
    for code in range(33, 256):
        try:
            char = bytes([code]).decode('cp1252')
        except UnicodeDecodeError:
            continue
        if not char.isspace() and code != 173:
            chars.append(char)
    buf = io.BytesIO()
    pdf = canvas.Canvas(buf, pagesize=(2000, 2000))
    for char in chars:
        pdf.setFont(font, 1000)
        pdf.drawString(200, 500, char)
        pdf.showPage()
    pdf.save()
    with pypdfium2.PdfDocument(buf.getvalue()) as doc:
        bounds = {}
        for page, char in zip(doc, chars):
            text = page.get_textpage()
            try:
                left, bottom, right, top = text.get_charbox(0)
                bounds[char] = [round((left-200)/1000, 6), round((bottom-500)/1000, 6),
                                round((right-200)/1000, 6), round((top-500)/1000, 6)]
            finally:
                text.close()
                page.close()
        metrics[font] = bounds
payload = json.dumps(metrics, ensure_ascii=True, separators=(',', ':'))
(root/'gotoquill/text-metrics.json').write_text(payload+'\n')
ts = '// Generated by scripts/generate-text-metrics.py. Unit-em visible glyph bounds.\nexport const textMetrics: Record<string, Record<string, number[]>> = '+payload+';\n'
(root/'packages/ts/src/text-metrics.ts').write_text(ts)
cloud = root/'cloud/worker-ts/src/text-metrics.ts'
if cloud.parent.exists():
    cloud.write_text(ts)
